def downgrade() -> None:
    """Drop the entire EMS schema.

    **Hand-written, replacing autogenerate's output.** Two things make the generated
    downgrade wrong on MySQL:

    1. It emits ``drop_index`` before ``drop_table``, and MySQL refuses to drop an index that
       a foreign key depends on (error 1553). Dropping the table removes its indexes anyway.
    2. The foreign keys in this schema contain legitimate cycles — ``users.employee_id``
       references ``employees`` while every table's ``created_by`` references ``users`` — so
       no single drop order satisfies all of them.

    Suspending constraint checks for the duration is therefore the only correct approach, and
    it is safe here precisely because every table is being dropped. Constraint checking is
    restored in a ``finally`` block so a failure part-way cannot leave the session with
    checks disabled.
    """
